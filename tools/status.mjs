// Builds STATUS.md (the live "who's doing what" board) from GitHub issues and PRs, so nobody hand-edits
// status. Run by .github/workflows/status.yml; needs GH_TOKEN and GITHUB_REPOSITORY. Fails loudly if
// GitHub can't be read, rather than writing a wrong board.
import { writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const repo = process.env.GITHUB_REPOSITORY || 'cillian1/belfast-wheel-app';
const headers = { Authorization: `Bearer ${process.env.GH_TOKEN}`, Accept: 'application/vnd.github+json' };
async function gh(path) {
  // local runs (no GH_TOKEN): go through the gh CLI instead
  if (!process.env.GH_TOKEN) return JSON.parse(execFileSync('gh', ['api', `repos/${repo}/${path}`], { encoding: 'utf8', maxBuffer: 1 << 26 }));
  const r = await fetch(`https://api.github.com/repos/${repo}/${path}`, { headers });
  if (!r.ok) throw new Error(`GitHub ${r.status} on ${path}`);
  return r.json();
}

const issues = (await gh('issues?state=open&per_page=100')).filter(i => !i.pull_request);
const prs = await gh('pulls?state=open&per_page=100');
const comments = await gh('issues/comments?sort=created&direction=desc&per_page=100');

// latest status-word comment per issue: BLOCKED / DONE wins over the issue's CURRENT line
const lastWord = {};
for (const c of comments) {
  const n = +c.issue_url.split('/').pop();
  if (lastWord[n]) continue;
  const m = c.body.match(/^(BLOCKED|DONE)\b[:\s]*(.*)/);
  if (m) lastWord[n] = { word: m[1], text: m[2].split('\n')[0].slice(0, 120), at: c.created_at.slice(0, 16) };
}
const prFor = n => prs.filter(p => new RegExp(`#${n}\\b`).test(`${p.title} ${p.body || ''}`));
const cell = s => String(s).replace(/\|/g, '/').replace(/\n/g, ' ');

function state(i) {
  const w = lastWord[i.number];
  if (w?.word === 'BLOCKED') return `BLOCKED: ${w.text}`;
  const p = prFor(i.number);
  if (w?.word === 'DONE') return 'Done, waiting to merge';
  if (p.length) return p.some(x => !x.draft) ? 'In review' : 'In progress';
  const cur = (i.body || '').match(/^CURRENT:\s*(.*)/m);
  if (cur && /ON HOLD/i.test(cur[1])) return 'On hold';
  return i.labels.some(l => ['copilot-task', 'renauw-task'].includes(l.name)) ? 'Started, no PR yet' : 'Not started';
}

const tasks = issues.filter(i => /^Task\b/.test(i.title)).sort((a, b) => a.number - b.number);
const rows = tasks.map(i => {
  const p = prFor(i.number).map(x => `#${x.number}${x.draft ? ' (draft)' : ''} → ${x.base.ref}`).join(', ') || '';
  return `| #${i.number} | ${cell(i.title)} | ${cell(state(i))} | ${p} |`;
});
const other = prs.filter(p => !tasks.some(t => prFor(t.number).includes(p)))
  .map(p => `- #${p.number} ${cell(p.title)} → ${p.base.ref}${p.draft ? ' (draft)' : ''}`);

writeFileSync('STATUS.md', `# Status board

Generated by \`tools/status.mjs\` from GitHub issues and PRs. **Don't edit by hand.** To change a task's
status, post on its issue: \`BLOCKED: <reason>\`, \`DONE: <task>\`, or update the issue's \`CURRENT:\` line.
The plan (order of work) lives in HANDOFF.md, which both Claude and Copilot may edit.

| Issue | Task | Status | PRs |
|---|---|---|---|
${rows.join('\n')}

${other.length ? `**Other open PRs**\n\n${other.join('\n')}\n` : ''}`);
console.log(`STATUS.md: ${rows.length} tasks, ${other.length} other PRs`);
